#!/usr/bin/env node
// Generates generated/GraphoTokens.kt (Jetpack Compose) from tokens.json. No dependencies.
//   node design/tokens/build-kotlin.mjs [--check]
// The file is written to generated/ and into the Android theme package. Android platform values (hit target 48) are baked in.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { load, tierOf, ext, here } from './tokens-model.mjs';
import { parseHex } from './contrast.mjs';

const M = load();
const camel = (p) => p.split(/[.\-]/).map((x, i) => (i ? x[0].toUpperCase() + x.slice(1) : x)).join('').replace(/^(\d)/, '_$1');
const pascal = (s) => s.split('-').map((x) => x[0].toUpperCase() + x.slice(1)).join('');
const leafValue = (t) => (typeof t.$value === 'string' && /^\{.+\}$/.test(t.$value) ? M.resolve(t.$value.slice(1, -1)).$value : t.$value);
const num = (s) => parseFloat(String(s));
const argb = (hex) => { const c = parseHex(hex); const h = (n) => Math.round(n).toString(16).padStart(2, '0').toUpperCase(); return `Color(0x${h(c.a * 255)}${h(c.r)}${h(c.g)}${h(c.b)})`; };
const sem = [...M.leaves].filter(([p]) => tierOf(p) === 'semantic').map(([p, t]) => [p.slice(9), t]);
const themable = sem.filter(([p]) => M.themed.has('semantic.' + p));
const resolved = (v, p) => { const o = v.overrides.get('semantic.' + p) ?? M.leaves.get('semantic.' + p); return leafValue(o); };

const L = ['// Generated by design/tokens/build-kotlin.mjs from tokens.json. Do not edit by hand.', 'package com.onemnemo.grapho.ui.theme', '', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.unit.dp', 'import androidx.compose.ui.unit.sp', 'import androidx.compose.animation.core.CubicBezierEasing', ''];
L.push('/** Every themable colour. One instance per theme variant. A missing value is a build error, never a fallback. */', 'data class GraphoColors(');
L.push(themable.map(([p]) => `    val ${camel(p)}: Color,`).join('\n'), ')', '', 'object GraphoThemes {');
for (const v of M.variants) {
  L.push(`    val ${camel(v.id)} = GraphoColors(`);
  L.push(themable.map(([p]) => `        ${camel(p)} = ${argb(resolved(v, p))},`).join('\n'), '    )');
}
L.push('    val all: Map<String, GraphoColors> = mapOf(' + M.variants.map((v) => `"${v.id}" to ${camel(v.id)}`).join(', ') + ')', '}', '');
L.push('/** Colours that are content, not chrome. No theme changes them. */', 'object GraphoContent {');
for (const [p, t] of sem) if (t.$type === 'color' && !M.themed.has('semantic.' + p)) L.push(`    val ${camel(p)} = ${argb(leafValue(t))}`);
L.push('}', '');
/* The pen wheel is a fixed dark instrument over any page, so its colours are components, not themed: one set for every theme. */
L.push('/** Pen wheel colours. The wheel is a fixed dark instrument, so no theme changes them. */', 'object GraphoWheel {');
for (const [p, t] of M.leaves) if (p.startsWith('component.wheel.') && t.$type === 'color') L.push(`    val ${camel(p.slice(16))} = ${argb(leafValue(t))}`);
L.push('}', '');
const dimTokens = sem.filter(([, t]) => t.$type === 'dimension');
const dens = dimTokens.filter(([, t]) => ext(t, 'compact') !== undefined);
L.push('/** Density. Resolved by the app (see tokens/README.md), never by a media query. */', 'data class GraphoMetrics(');
L.push(dens.map(([p]) => `    val ${camel(p)}: androidx.compose.ui.unit.Dp,`).join('\n'), ')', '');
const androidVal = (t) => (typeof ext(t, 'platform')?.android === 'string' ? ext(t, 'platform').android : null);
const metric = (mode) => 'GraphoMetrics(' + dens.map(([p, t]) => `${camel(p)} = ${num(mode ? leafValue({ $value: ext(t, 'compact') }) : leafValue({ $value: androidVal(t) ?? t.$value }))}.dp`).join(', ') + ')';
L.push(`val GraphoTouch = ${metric(false)}`, `val GraphoCompact = ${metric(true)}`, '', 'object GraphoSpace {');
for (const [p, t] of dimTokens) if (!ext(t, 'compact') && !p.startsWith('layout.breakpoint')) L.push(`    val ${camel(p)} = ${num(leafValue({ $value: androidVal(t) ?? t.$value }))}.dp`);
L.push('}', '', 'object GraphoMotion {');
for (const [p, t] of sem) {
  if (t.$type === 'duration') L.push(`    const val ${camel(p)}Ms = ${Math.round(num(leafValue(t)))}`);
  if (t.$type === 'cubicBezier') L.push(`    val ${camel(p)} = CubicBezierEasing(${leafValue(t).map((x) => x + 'f').join(', ')})`);
}
L.push('    /** Under reduced motion every duration is 0 and the enter easing is the standard one. */', '}', '', '/** Layer order. Compose has no z-index across windows: see tokens/README.md for how the shell orders them. */', 'object GraphoLayer {');
for (const [p, t] of sem) if (p.startsWith('z.')) L.push(`    const val ${camel(p.slice(2))} = ${leafValue(t)}`);
L.push('}', '', '/** Type. Sizes and tracking are sp and em so the system text size setting applies. */', 'data class GraphoTextSpec(val sizeSp: Float, val lineHeightMultiple: Float, val weight: Int, val trackingEm: Float)', 'object GraphoType {');
for (const [p, t] of sem) if (t.$type === 'typography') { const v = t.$value; const r = (x) => leafValue({ $value: x }); L.push(`    val ${camel(p.slice(5))} = GraphoTextSpec(${num(r(v.fontSize))}f, ${num(r(v.lineHeight))}f, ${r(v.fontWeight)}, ${num(r(v.letterSpacing))}f)`); }
L.push('}', '');
const out = L.join('\n');
// The Android shell compiles its own copy of the file, so both are written and checked together and cannot drift.
const targets = [join(here, 'generated', 'GraphoTokens.kt'), join(here, '..', '..', 'android', 'app', 'src', 'main', 'java', 'com', 'onemnemo', 'grapho', 'ui', 'theme', 'GraphoTokens.kt')];
if (process.argv.includes('--check')) {
  const stale = targets.filter((f) => !existsSync(f) || readFileSync(f, 'utf8') !== out);
  if (stale.length) { console.error(`${stale.join(', ')} out of date. Run: node design/tokens/build-kotlin.mjs`); process.exit(1); }
  console.log('GraphoTokens.kt is up to date in both places');
} else for (const f of targets) { mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, out); console.log(`wrote ${f}`); }

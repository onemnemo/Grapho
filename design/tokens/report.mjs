// Generates themes/contrast-matrix.md and tokens/usage-rules.json from the matrix results.
import { evalMatrix, failures, deltaE } from './contrast.mjs';

export const MIN_DISTANCE = 0.03; // OKLab distance between any two variants, on base and on control

export const runMatrix = (M) => {
  const out = {};
  for (const v of M.variants) { const map = M.mapOf(v); out[v.id] = { map, results: evalMatrix((k) => map[k], M.spec) }; }
  return out;
};

// The pair list is an allow-list: a foreground may sit only on hosts a pair guarantees.
export const usageRules = (M) => {
  const g = M.spec.groups, list = (x) => (Array.isArray(x) ? x : x.startsWith('$') ? g[x.slice(1)] : [x]).flatMap((y) => (y.startsWith('$') ? g[y.slice(1)] : [y]));
  const allowedSet = {};
  for (const p of M.spec.pairs) if (p.req !== 'exempt') for (const fg of list(p.fg)) for (const bg of list(p.bg)) (allowedSet[fg] ??= new Set()).add(bg);
  const hosts = [...new Set([...g.surfaces, ...g.fills, ...g.stateTints, 'highlight.match', 'media.glass', 'media.chip', 'media.chip-hover', ...g.primaryStates, ...g.secondaryStates])];
  const allowed = {}, forbidden = {};
  for (const fg of ['text.default', 'text.muted', 'text.subtle', 'text.on-action', 'action.secondary.fg', 'media.text', ...g.stateFg]) {
    allowed[fg] = hosts.filter((h) => allowedSet[fg]?.has(h));
    forbidden[fg] = hosts.filter((h) => !allowedSet[fg]?.has(h));
  }
  return { allowed, forbidden };
};

export const distances = (M, matrix) => {
  const ids = M.variants.map((v) => v.id);
  const rows = [];
  for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) {
    const a = matrix[ids[i]].map, b = matrix[ids[j]].map;
    rows.push({ a: ids[i], b: ids[j], base: deltaE(a['surface.base'], b['surface.base']), control: deltaE(a['surface.control'], b['surface.control']), text: deltaE(a['text.default'], b['text.default']) });
  }
  return rows;
};

export const matrixMarkdown = (M, matrix, rules, dist) => {
  const L = [];
  L.push('# Contrast matrix', '', 'Generated by `design/tokens/build-tokens.mjs`. Do not edit by hand. The pair list lives in `tokens.json` under `$extensions.grapho.pairs`; the build fails if any graded pair misses its requirement in any variant.', '');
  L.push('## Requirements', '', '| Requirement | Ratio | Applies to |', '|---|---|---|', '| text | 4.5:1 | Text and icons carrying meaning, at any size |', '| large | 3:1 | Large text (18.66 px bold or 24 px) |', '| ui | 3:1 | Edges, rings, indicators and fills that identify a component or its state (WCAG 1.4.11) |', '| number | as stated | Ink on the page is 7:1 |', '| exempt | none | Computed and shown, with a reason |', '');
  L.push('Alpha colours are composited over the host surface in gamma encoded sRGB, rounded the way the browser rounds. A pair "over" a host is graded on every host in its list. `any` pairs pass when one colour of the pair reaches the ratio (the two-tone focus ring and handle).', '');
  L.push('## Result per variant', '', '| Variant | Graded pairs | Pass | Fail | Lowest margin | Exempt pairs |', '|---|---:|---:|---:|---|---:|');
  for (const v of M.variants) {
    const r = matrix[v.id].results, graded = r.filter((x) => !x.exempt);
    const worst = graded.reduce((a, b) => (b.eff / b.need < a.eff / a.need ? b : a));
    L.push(`| ${v.id} | ${graded.length} | ${graded.filter((x) => x.ok).length} | ${failures(r).length} | ${worst.eff.toFixed(2)}:1 for ${worst.fg} on ${worst.bg}${worst.host ? ' over ' + worst.host : ''} (needs ${worst.need}) | ${r.length - graded.length} |`);
  }
  L.push('', '## Declared pairs', '', '| Pair | Foreground | Background | Over | Requirement |', '|---|---|---|---|---|');
  const g = M.spec.groups;
  const nm = (x) => (Array.isArray(x) ? x.map((y) => (y.startsWith('$') ? y : '`' + y.replace(/\./g, '/') + '`')).join(', ') : x.startsWith('$') ? `group ${x.slice(1)}` : '`' + x.replace(/\./g, '/') + '`');
  for (const p of M.spec.pairs) L.push(`| ${p.id} | ${nm(p.fg)} | ${nm(p.bg)} | ${p.over ? nm(p.over) : ''} | ${p.req}${p.reason ? ': ' + p.reason : ''} |`);
  L.push('', 'Groups:', '');
  for (const [k, v] of Object.entries(g)) L.push(`- **${k}**: ${v.map((x) => '`' + x.replace(/\./g, '/') + '`').join(', ')}`);
  L.push('', '## Usage rules (generated)', '', 'The pair list is an allow-list: a foreground may sit only on the hosts listed for it, and anything unlisted is forbidden. `usage-rules.json` carries the same data for `scripts/check-design.mjs`.', '');
  for (const [fg, hs] of Object.entries(rules.allowed)) L.push(`- \`${fg.replace(/\./g, '/')}\` is allowed on: ${hs.map((h) => '`' + h.replace(/\./g, '/') + '`').join(', ')}. Nothing else.`);
  L.push('', '## Distance between variants', '', `OKLab distance. The target is at least ${MIN_DISTANCE} between the base surfaces of any two variants and between their control surfaces, so no two themes look alike. The build fails below it.`, '', '| Variant A | Variant B | Base | Control | Text |', '|---|---|---:|---:|---:|');
  for (const d of dist) L.push(`| ${d.a} | ${d.b} | ${d.base.toFixed(3)}${d.base < MIN_DISTANCE ? ' LOW' : ''} | ${d.control.toFixed(3)}${d.control < MIN_DISTANCE ? ' LOW' : ''} | ${d.text.toFixed(3)} |`);
  L.push('');
  return L.join('\n');
};
